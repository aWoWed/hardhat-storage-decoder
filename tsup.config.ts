import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { defineConfig, type Options } from 'tsup';

/**
 * One tsup config per emitted entrypoint, each pinned to its own tsconfig.
 *
 * The two adapter builds MUST use `tsconfig.hardhat2.json` / `tsconfig.hardhat3.json`
 * so each compiles against its own Hardhat major's real types via the npm-alias +
 * `paths` mechanism. See `docs/build-internals.md`.
 *
 * `hardhat` and `@noble/hashes` are external: `hardhat` is a peer dependency and
 * `@noble/hashes` is a declared runtime dependency, so both resolve from the
 * consumer's own `node_modules` rather than being bundled (bundling a declared
 * dependency would ship it twice).
 */
const shared: Options = {
  format: ['cjs', 'esm'],
  dts: true,
  sourcemap: true,
  clean: false,
  splitting: false,
  treeshake: true,
  target: 'node18',
  external: ['hardhat', '@noble/hashes'],
  // Only `js` is overridable here. tsup 8.5.x derives the DECLARATION extension from
  // `defaultOutExtension` directly (`tsup/dist/index.js`, `runDtsRollup`) and ignores a
  // `dts` key returned from this callback. For a `"type": "commonjs"` package that means
  // the CJS declarations are emitted as `index.d.ts` (not `index.d.cts`), which is why
  // `package.json`'s `require` conditions point at `.d.ts`. Changing either side without
  // the other breaks type resolution for every TypeScript consumer.
  outExtension({ format }) {
    return { js: format === 'cjs' ? '.cjs' : '.mjs' };
  },
};

/**
 * Replace the Hardhat 2 ES-module bundle with a wrapper over the CommonJS one.
 *
 * tsup's own `dist/hardhat2/index.mjs` cannot be loaded: it imports `hardhat/config`, and
 * Hardhat 2 has no `exports` map, so Node's ES-module resolver looks for a file literally named
 * `config` and fails with `ERR_MODULE_NOT_FOUND` (`require` adds the `.js`). Loading it would
 * also be wrong if it worked: a second copy of the plugin would register itself with Hardhat a
 * second time and carry its own error classes, so `instanceof` against an error thrown by
 * `hre.storageDecoder` would be false.
 *
 * The wrapper imports `./index.cjs` and re-exports each of its names, so both module formats
 * share one plugin instance. The names are read from the `exports.<name> = ` lines of the
 * CommonJS bundle that was just written, so the list cannot be edited out of step with it;
 * `scripts/check-dist-entrypoints.mjs` loads both and fails if they ever differ.
 *
 * The `esm` format stays in the tsup run because it is what emits `index.d.mts`, which still
 * describes the wrapper exactly (same names, same types).
 */
function writeHardhat2EsmWrapper(): void {
  const outDir = 'dist/hardhat2';
  const cjs = readFileSync(`${outDir}/index.cjs`, 'utf8');
  const names = [...cjs.matchAll(/^exports\.([A-Za-z_$][\w$]*) = /gm)].map((match) => match[1]);
  if (names.length === 0 || names.includes('default')) {
    throw new Error(
      `Cannot write the Hardhat 2 ES-module wrapper: expected named "exports.<name> = " lines ` +
        `and no default export in ${outDir}/index.cjs, found [${names.join(', ')}]`
    );
  }
  const lines = [
    '// Generated by tsup.config.ts. The CommonJS build is the only copy of the plugin; this file',
    '// re-exports it by name so that `import` and `require` share one instance.',
    "import plugin from './index.cjs';",
    '',
    ...names.map((name) => `export const ${name} = plugin.${name};`),
    '',
  ];
  writeFileSync(`${outDir}/index.mjs`, lines.join('\n'));
  // The map tsup wrote describes the bundle that was just replaced.
  rmSync(`${outDir}/index.mjs.map`, { force: true });
}

const configs: Options[] = [
  {
    ...shared,
    name: 'root',
    clean: true,
    entry: { index: 'src/index.ts' },
    outDir: 'dist',
    tsconfig: 'tsconfig.json',
  },
];

// The adapters are built by separate work; guard on existence so `npm run build`
// is runnable while they land. Once `src/hardhat2/index.ts` exists it is picked up
// automatically — no config edit needed.
if (existsSync('src/hardhat2/index.ts')) {
  configs.push({
    ...shared,
    name: 'hardhat2',
    entry: { index: 'src/hardhat2/index.ts' },
    outDir: 'dist/hardhat2',
    tsconfig: 'tsconfig.hardhat2.json',
    // tsup calls this once both formats of this entry are on disk.
    async onSuccess() {
      writeHardhat2EsmWrapper();
    },
  });
}

if (existsSync('src/hardhat3/index.ts')) {
  configs.push({
    ...shared,
    name: 'hardhat3',
    entry: { index: 'src/hardhat3/index.ts' },
    outDir: 'dist/hardhat3',
    tsconfig: 'tsconfig.hardhat3.json',
  });
}

export default defineConfig(configs);
