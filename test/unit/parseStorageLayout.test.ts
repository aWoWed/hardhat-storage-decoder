import { describe, expect, it } from 'vitest';
import {
  getTypeInfo,
  getVariable,
  parseFixedArrayLength,
} from '../../src/core/layout/parseStorageLayout.js';
import { UnsupportedTypeError, VariableNotFoundError } from '../../src/core/query/errors.js';
import { SOLC_VERSION, loadBareLayout, loadLayout } from './helpers.js';

describe('fixtures', () => {
  it('are generated by the pinned solc', () => {
    expect(SOLC_VERSION).toMatch(/^0\.8\.26\+/);
  });
});

describe('parseStorageLayout', () => {
  it('coerces slot to bigint and offset/numberOfBytes to number', () => {
    const layout = loadLayout('SimpleStorage.sol:SimpleStorage');
    const count = getVariable(layout, 'count');
    expect(count.slot).toBe(0n);
    expect(typeof count.slot).toBe('bigint');
    expect(count.offset).toBe(0);
    expect(getTypeInfo(layout, count.typeId).numberOfBytes).toBe(32);
  });

  it('resolves inherited variables into one flat, correctly ordered layout', () => {
    const layout = loadLayout('InheritedStorage.sol:InheritedStorage');
    expect(layout.variables.map((v) => [v.label, v.slot, v.offset])).toEqual([
      ['baseValue', 0n, 0],
      ['basePacked', 1n, 0],
      // The child's first variable packs into the parent's trailing slot space.
      ['midPacked', 1n, 16],
      ['midAddress', 2n, 0],
      ['childValue', 3n, 0],
      ['childMap', 4n, 0],
    ]);
  });
});

describe('getVariable', () => {
  const layout = loadLayout('SimpleStorage.sol:SimpleStorage');

  it('throws a descriptive error naming the contract and the available variables', () => {
    expect(() => getVariable(layout, 'nope')).toThrow(VariableNotFoundError);
    try {
      getVariable(layout, 'nope');
    } catch (error) {
      expect((error as Error).message).toContain('SimpleStorage');
      expect((error as Error).message).toContain('count');
    }
  });

  it('distinguishes constants and immutables from a typo', () => {
    for (const name of ['MAX_COUNT', 'deployer']) {
      expect(() => getVariable(layout, name)).toThrow(VariableNotFoundError);
      try {
        getVariable(layout, name);
      } catch (error) {
        expect((error as Error).message).toContain('constant or immutable');
        expect((error as VariableNotFoundError).options.isConstantOrImmutable).toBe(true);
      }
    }
  });
});

describe('getTypeInfo', () => {
  it('dispatches on solc encoding, not on the label', () => {
    const layout = loadLayout('ArrayStorage.sol:ArrayStorage');
    expect(getTypeInfo(layout, 't_array(t_uint96)dyn_storage').kind).toBe('dynamicArray');
    expect(getTypeInfo(layout, 't_array(t_uint8)10_storage').kind).toBe('fixedArray');
    const pair = Object.values(layout.types).find((type) => type.label === 'struct ArrayStorage.Pair');
    expect(pair).toBeDefined();
    expect(getTypeInfo(layout, pair!.id).kind).toBe('struct');
    expect(getTypeInfo(layout, 't_uint96').kind).toBe('value');
  });

  it('resolves t_contract to address and t_enum to a small uint', () => {
    const layout = loadLayout('EnumAndContractStorage.sol:EnumAndContractStorage');
    const token = getTypeInfo(layout, getVariable(layout, 'token').typeId);
    expect(token.valueKind).toEqual({ family: 'address' });

    const status = getTypeInfo(layout, getVariable(layout, 'status').typeId);
    expect(status.valueKind).toEqual({ family: 'uint', bits: 8, bytes: 1 });
    expect(status.numberOfBytes).toBe(1);
  });

  it('resolves each user-defined value type to its own underlying rule', () => {
    const layout = loadLayout('UserDefinedTypes.sol:UserDefinedTypes');
    const kindOf = (name: string) =>
      getTypeInfo(layout, getVariable(layout, name).typeId).valueKind;

    expect(kindOf('idVar')).toEqual({ family: 'bytesN', size: 32 });
    expect(kindOf('signedVar')).toEqual({ family: 'int', bits: 128, bytes: 16 });
    expect(kindOf('amountVar')).toEqual({ family: 'uint', bits: 96, bytes: 12 });
  });

  it('marks a user-defined value type unresolved when no AST information is supplied', () => {
    // storageLayout alone genuinely cannot tell `type Id is bytes32` from `type Id is uint256`.
    const layout = loadBareLayout('UserDefinedTypes.sol:UserDefinedTypes');
    expect(getTypeInfo(layout, getVariable(layout, 'idVar').typeId).valueKind).toEqual({
      family: 'unresolvedUserDefinedValueType',
      name: 'Id',
      numberOfBytes: 32,
    });
  });

  it('treats string and bytes as distinct dynamic-bytes types', () => {
    const layout = loadLayout('StringStorage.sol:StringStorage');
    expect(getTypeInfo(layout, 't_string_storage')).toMatchObject({
      kind: 'dynamicBytes',
      valueKind: { family: 'string' },
    });
    expect(getTypeInfo(layout, 't_bytes_storage')).toMatchObject({
      kind: 'dynamicBytes',
      valueKind: { family: 'bytes' },
    });
  });

  it('throws for a type the layout does not define', () => {
    const layout = loadLayout('SimpleStorage.sol:SimpleStorage');
    expect(() => getTypeInfo(layout, 't_nonsense')).toThrow(UnsupportedTypeError);
  });
});

describe('parseFixedArrayLength', () => {
  it('parses the length from the type identifier', () => {
    expect(parseFixedArrayLength('t_array(t_uint8)10_storage')).toBe(10);
    expect(parseFixedArrayLength('t_array(t_uint256)3_storage')).toBe(3);
    expect(parseFixedArrayLength('t_array(t_struct(Inner)223_storage)2_storage')).toBe(2);
  });

  it('does NOT come from a numberOfBytes ratio', () => {
    // solc reports numberOfBytes 32 for uint8[10]; 32 / 1 = 32, which would be wrong.
    const layout = loadLayout('ArrayStorage.sol:ArrayStorage');
    const type = getTypeInfo(layout, 't_array(t_uint8)10_storage');
    expect(type.numberOfBytes).toBe(32);
    expect(getTypeInfo(layout, 't_uint8').numberOfBytes).toBe(1);
    expect(type.fixedLength).toBe(10);
  });

  it('falls back to the label, then throws', () => {
    expect(parseFixedArrayLength('mystery', 'uint8[7]')).toBe(7);
    expect(() => parseFixedArrayLength('mystery')).toThrow(UnsupportedTypeError);
  });
});
